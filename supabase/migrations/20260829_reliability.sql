begin;

alter table public.payments alter column payment_id drop not null;
alter table public.payments add column if not exists idempotency_key text;
alter table public.payments add column if not exists amount numeric(12, 2);
alter table public.payments add column if not exists currency text;
alter table public.payments add column if not exists confirmation_url text;
alter table public.payments add column if not exists provider_expires_at timestamptz;
alter table public.payments add column if not exists next_check_at timestamptz default now();
alter table public.payments add column if not exists check_attempts integer not null default 0;
alter table public.payments add column if not exists succeeded_at timestamptz;
alter table public.payments add column if not exists canceled_at timestamptz;
alter table public.payments add column if not exists reminder_1_sent_at timestamptz;
alter table public.payments add column if not exists reminder_2_sent_at timestamptz;
alter table public.payments add column if not exists source text not null default 'organic';
alter table public.payments add column if not exists last_error text;

update public.payments
set idempotency_key = 'legacy-' || id::text
where idempotency_key is null;

alter table public.payments alter column idempotency_key set not null;
create unique index if not exists payments_idempotency_key_idx
  on public.payments (idempotency_key);

with duplicate_pending as (
  select id,
         row_number() over (partition by telegram_id order by created_at desc, id desc) as position
  from public.payments
  where status in ('creating', 'pending')
)
update public.payments p
set status = 'canceled', canceled_at = now(), last_error = 'superseded during reliability migration'
from duplicate_pending d
where p.id = d.id and d.position > 1;

create unique index if not exists payments_one_open_per_user_idx
  on public.payments (telegram_id)
  where status in ('creating', 'pending');
create index if not exists payments_due_check_idx
  on public.payments (next_check_at)
  where status in ('creating', 'pending');

create table if not exists public.bot_users (
  telegram_id bigint primary key,
  source text not null default 'organic',
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.access_deliveries (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null unique,
  payment_id text not null unique,
  status text not null default 'pending',
  invite_link text,
  invite_expires_at timestamptz,
  sent_at timestamptz,
  attempt_count integer not null default 0,
  next_retry_at timestamptz not null default now(),
  claimed_at timestamptz,
  last_error text,
  last_alerted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint access_deliveries_status_check
    check (status in ('pending', 'processing', 'link_ready', 'delivered', 'failed'))
);

insert into public.access_deliveries (
  telegram_id, payment_id, status, sent_at, next_retry_at, created_at, updated_at
)
select distinct on (telegram_id)
  telegram_id,
  payment_id,
  case when invite_sent then 'delivered' else 'pending' end,
  case when invite_sent then updated_at else null end,
  now(),
  created_at,
  updated_at
from public.payments
where status = 'succeeded' and payment_id is not null
order by telegram_id, created_at desc
on conflict do nothing;

create index if not exists access_deliveries_due_idx
  on public.access_deliveries (next_retry_at)
  where status in ('pending', 'failed', 'link_ready', 'processing');

create table if not exists public.funnel_events (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null,
  event_type text not null,
  source text not null default 'organic',
  payment_id text,
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists funnel_events_created_at_idx
  on public.funnel_events (created_at desc);
create index if not exists funnel_events_type_created_at_idx
  on public.funnel_events (event_type, created_at desc);

create or replace function public.claim_access_delivery(
  p_payment_id text,
  p_telegram_id bigint
)
returns setof public.access_deliveries
language plpgsql
security invoker
as $$
begin
  insert into public.access_deliveries (telegram_id, payment_id)
  values (p_telegram_id, p_payment_id)
  on conflict do nothing;

  return query
  update public.access_deliveries
  set status = 'processing',
      attempt_count = attempt_count + 1,
      claimed_at = now(),
      updated_at = now()
  where payment_id = p_payment_id
    and telegram_id = p_telegram_id
    and next_retry_at <= now()
    and (
      status in ('pending', 'failed', 'link_ready')
      or (status = 'processing' and claimed_at < now() - interval '5 minutes')
    )
  returning *;
end;
$$;

drop trigger if exists access_deliveries_set_updated_at on public.access_deliveries;
create trigger access_deliveries_set_updated_at
before update on public.access_deliveries
for each row execute function public.set_updated_at();

alter table public.payments enable row level security;
alter table public.bot_users enable row level security;
alter table public.access_deliveries enable row level security;
alter table public.funnel_events enable row level security;

revoke all on table public.payments from anon, authenticated;
revoke all on table public.bot_users from anon, authenticated;
revoke all on table public.access_deliveries from anon, authenticated;
revoke all on table public.funnel_events from anon, authenticated;
revoke execute on function public.claim_access_delivery(text, bigint) from public, anon, authenticated;
grant execute on function public.claim_access_delivery(text, bigint) to service_role;

commit;
